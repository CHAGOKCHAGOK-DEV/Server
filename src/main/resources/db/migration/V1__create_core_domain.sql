CREATE TABLE installations (
    id UUID NOT NULL,
    token_hash CHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_installations PRIMARY KEY (id),
    CONSTRAINT uk_installations_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_installations_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_installations_status CHECK (status IN ('ACTIVE', 'REVOKED'))
);

CREATE TABLE copilots (
    installation_id UUID NOT NULL,
    nickname VARCHAR(30) NOT NULL,
    age_group VARCHAR(20) NOT NULL,
    mission_intensity VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_copilots PRIMARY KEY (installation_id),
    CONSTRAINT fk_copilots_installation FOREIGN KEY (installation_id) REFERENCES installations (id),
    CONSTRAINT ck_copilots_nickname CHECK (length(trim(nickname)) > 0),
    CONSTRAINT ck_copilots_age_group CHECK (age_group IN ('AGE_5_6', 'AGE_7_8', 'AGE_9_10')),
    CONSTRAINT ck_copilots_mission_intensity CHECK (mission_intensity IN ('LOW', 'NORMAL', 'HIGH'))
);

CREATE TABLE mission_packs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(50) NOT NULL,
    version INTEGER NOT NULL,
    schema_version INTEGER NOT NULL DEFAULT 1,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_mission_packs PRIMARY KEY (id),
    CONSTRAINT uk_mission_packs_code_version UNIQUE (code, version),
    CONSTRAINT ck_mission_packs_code CHECK (length(trim(code)) > 0),
    CONSTRAINT ck_mission_packs_version CHECK (version > 0),
    CONSTRAINT ck_mission_packs_schema_version CHECK (schema_version > 0),
    CONSTRAINT ck_mission_packs_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

CREATE TABLE missions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    mission_pack_id BIGINT NOT NULL,
    code VARCHAR(50) NOT NULL,
    trigger_type VARCHAR(50) NOT NULL,
    config JSONB NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_missions PRIMARY KEY (id),
    CONSTRAINT fk_missions_pack FOREIGN KEY (mission_pack_id) REFERENCES mission_packs (id),
    CONSTRAINT uk_missions_pack_code UNIQUE (mission_pack_id, code),
    CONSTRAINT ck_missions_code CHECK (length(trim(code)) > 0),
    CONSTRAINT ck_missions_trigger_type CHECK (trigger_type IN ('TURN_SIGNAL_OFF', 'WIPER_ON', 'LOW_BEAM_ON', 'NAVI_NEXT_TURN', 'NEAR_DESTINATION')),
    CONSTRAINT ck_missions_config_object CHECK (jsonb_typeof(config) = 'object')
);

CREATE TABLE trips (
    id UUID NOT NULL,
    installation_id UUID NOT NULL,
    mission_pack_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    end_reason VARCHAR(30) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ NOT NULL,
    payload_hash CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_trips PRIMARY KEY (id),
    CONSTRAINT fk_trips_installation FOREIGN KEY (installation_id) REFERENCES installations (id),
    CONSTRAINT fk_trips_mission_pack FOREIGN KEY (mission_pack_id) REFERENCES mission_packs (id),
    CONSTRAINT ck_trips_status CHECK (status IN ('COMPLETED', 'INTERRUPTED')),
    CONSTRAINT ck_trips_end_reason CHECK (end_reason IN ('PARKING_BRAKE', 'STOP_TIMEOUT', 'MANUAL_STOP', 'APP_INTERRUPTED', 'SDK_DISCONNECTED', 'UNKNOWN')),
    CONSTRAINT ck_trips_period CHECK (ended_at >= started_at),
    CONSTRAINT ck_trips_payload_hash CHECK (payload_hash ~ '^[0-9a-f]{64}$')
);

CREATE TABLE mission_results (
    id UUID NOT NULL,
    trip_id UUID NOT NULL,
    mission_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    participated BOOLEAN NOT NULL DEFAULT FALSE,
    is_correct BOOLEAN,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_mission_results PRIMARY KEY (id),
    CONSTRAINT fk_mission_results_trip FOREIGN KEY (trip_id) REFERENCES trips (id),
    CONSTRAINT fk_mission_results_mission FOREIGN KEY (mission_id) REFERENCES missions (id),
    CONSTRAINT ck_mission_results_status CHECK (status IN ('COMPLETED', 'EXPIRED', 'CANCELLED')),
    CONSTRAINT ck_mission_results_period CHECK (ended_at >= started_at),
    CONSTRAINT ck_mission_results_correct_participation CHECK (participated OR is_correct IS NULL)
);

CREATE INDEX idx_mission_packs_status_version ON mission_packs (status, version DESC);
CREATE INDEX idx_missions_pack ON missions (mission_pack_id);
CREATE INDEX idx_trips_installation_started ON trips (installation_id, started_at DESC);
CREATE INDEX idx_mission_results_trip ON mission_results (trip_id);
CREATE INDEX idx_mission_results_mission ON mission_results (mission_id);
